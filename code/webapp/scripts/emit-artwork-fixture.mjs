#!/usr/bin/env node
/**
 * Regenerate firmware/test/test_artwork/fixture_artwork.h from the app's real artwork encoder.
 *
 * WHY THIS EXISTS: the two sides of the artwork transfer are written in different languages
 * (TypeScript here, C in lib/upload), with independently hand-written struct layouts. Field
 * ORDER, FIELD WIDTH and ENDIANNESS all have to agree, and neither side's own tests can catch a
 * disagreement — the app checks its output against its own expectations, and the C tests would
 * otherwise check hand-built bytes against the C struct. Both suites can pass while the real
 * transfer fails on the device.
 *
 * So the C side parses THIS capture: bytes produced by webapp/src/transfer/artwork.ts, for the
 * shipped two-page layout. It is generated, never hand-edited, so it cannot drift from the
 * encoder it claims to be a capture of.
 *
 * Usage:  node scripts/emit-artwork-fixture.mjs
 *         (from code/webapp/)
 *
 * `tsx` is used to import the TypeScript modules directly. The encoder is ESM and uses the
 * platform CompressionStream, so no loader shim is needed beyond tsx itself.
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const webapp = resolve(here, '..');
const outFile = resolve(webapp, '..', 'firmware', 'test', 'test_artwork', 'fixture_artwork.h');

/* A small program run through tsx: build each shipped page's static layer with the SAME code the
 * editor and the upload path use (buildStaticLayer + artworkForPage), encode the set, and print
 * the bytes as JSON. Doing it in a child process keeps this script from needing a TS build step
 * for the app's module graph.
 *
 * The await is wrapped in an async main() rather than left top-level: tsx's `-e` evaluates as CJS,
 * where top-level await is a parse error ("Top-level await is currently not supported with the
 * cjs output format"). */
const program = `
import { encodeArtwork } from './src/transfer/artwork.ts';
import { artworkForPage, PAGE_ARTWORK } from './src/presets/default-layout.ts';
import { buildStaticLayer } from './src/canvas/render.ts';

async function main() {
  const layers = PAGE_ARTWORK.map((_, i) => {
    const art = artworkForPage(i);
    return buildStaticLayer(
      art.labels.map((l) => ({ x: l.x, y: l.y, text: l.text, font: l.font })),
      art.rules.map((r) => ({ y: r.y, thickness: r.thickness, inset: r.inset })),
    ).data;
  });

  const { blob, crc, pageCount } = await encodeArtwork(layers);
  process.stdout.write(JSON.stringify({ bytes: Array.from(blob), crc, pageCount }));
}
main();
`;

const json = execFileSync('npx', ['tsx', '-e', program], {
  cwd: webapp,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});
const { bytes, crc, pageCount } = JSON.parse(json);

if (!Array.isArray(bytes) || bytes.length === 0) {
  console.error('emitter: the encoder produced no bytes — refusing to write a stub fixture');
  process.exit(1);
}

const rows = [];
for (let i = 0; i < bytes.length; i += 16) {
  rows.push('    ' + bytes.slice(i, i + 16).map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ') + ',');
}

const header = `#pragma once

/* GENERATED by code/webapp/scripts/emit-artwork-fixture.mjs — DO NOT EDIT BY HAND.
 *
 * A REAL artwork blob emitted by webapp/src/transfer/artwork.ts for the shipped ${pageCount}-page
 * layout, captured so the firmware parser is checked against the bytes the web app actually
 * produces rather than against a hand-built stand-in that could differ in field order or
 * endianness without any test noticing. Regenerate with:
 *   cd code/webapp && node scripts/emit-artwork-fixture.mjs
 */

#define FIXTURE_ART_CRC ${crc}u
#define FIXTURE_ART_LEN ${bytes.length}u
static const unsigned char FIXTURE_ART[] = {
${rows.join('\n')}
};
`;

writeFileSync(outFile, header);
console.log(`wrote ${outFile} (${bytes.length} bytes, crc ${crc}, ${pageCount} pages)`);
